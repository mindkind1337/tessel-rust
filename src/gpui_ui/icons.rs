/// Renders the 6-tile Tessel geometric mosaic logo (`BrandLogo.vue`) using theme accent + surfaces.
pub fn render_brand_logo(tokens: &GpuiThemeTokens) -> impl IntoElement {
    let tile = |color: Rgba| div().w(px(5.0)).h(px(5.0)).rounded(px(1.2)).bg(color);
    div()
        .flex()
        .flex_col()
        .gap(px(1.5))
        .justify_center()
        .items_center()
        .child(
            div()
                .flex()
                .gap(px(1.5))
                .child(tile(tokens.accent))
                .child(tile(super::theme::rgba_with_alpha(tokens.accent, 0.72)))
                .child(tile(super::theme::rgba_with_alpha(tokens.accent, 0.42))),
        )
        .child(
            div()
                .flex()
                .gap(px(1.5))
                .child(tile(super::theme::rgba_with_alpha(tokens.accent, 0.55)))
                .child(tile(tokens.accent))
                .child(tile(super::theme::rgba_with_alpha(tokens.accent, 0.85))),
        )
}
